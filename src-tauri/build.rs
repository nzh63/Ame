#[cfg(target_os = "windows")]
fn build_ppocr() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let ppocr_dir = std::path::Path::new(&manifest_dir).join("native/ppocr-ffi");
    let profile = env::var("PROFILE").unwrap_or_else(|_| "debug".into());
    let config_dir = if profile == "release" {
        "Release"
    } else {
        "Debug"
    };
    // Cargo's target dir: `CARGO_TARGET_DIR` when customized, otherwise
    // `<manifest_dir>/target` (NOT the repo root).
    let target_dir = env::var("CARGO_TARGET_DIR")
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|_| std::path::Path::new(&manifest_dir).join("target"));

    // DLL 必须与被编译的应用同架构（进程内加载）。跟随 cargo 的目标架构：
    // x86_64 → x64，x86（i686-pc-windows-msvc，32 位构建）→ x86。ncnn 与
    // opencv-mobile 的预编译包两个架构都有，由 CMake 的 -DARCH 选择。
    let target_arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_else(|_| "x86_64".into());
    let (cmake_arch, generator_platform) = match target_arch.as_str() {
        "x86" => ("x86", "Win32"),
        _ => ("x64", "x64"),
    };
    // 显式 `--target <triple>` 时产物在 <target>/<triple>/<profile>，否则
    // 在 <target>/<profile>`。按 OUT_DIR 判断本次调用的实际布局，避免把
    // 交叉构建的 DLL 覆盖到宿主布局（反之亦然）。
    let target_triple = env::var("TARGET").unwrap_or_default();
    let out_dir = env::var("OUT_DIR").unwrap_or_default();
    let uses_triple_layout = !target_triple.is_empty()
        && std::path::Path::new(&out_dir).starts_with(target_dir.join(&target_triple));
    let profile_dir = if uses_triple_layout {
        target_dir.join(&target_triple).join(&profile)
    } else {
        target_dir.join(&profile)
    };

    // Native sources are tracked so Cargo only re-runs this script when one
    // of them actually changes (otherwise `yarn dev` re-enters build.rs on
    // every invocation).
    let sources = walk_files(&ppocr_dir);
    track_files(&ppocr_dir);

    // The DLL is also distributed under build/static/native/bin (bundled into
    // packaged apps). When it already exists and is newer than every source
    // file, reuse it instead of re-running CMake — mirrors the old
    // `yarn build:native` incremental behavior.
    let static_bin = std::path::Path::new(&manifest_dir)
        .parent()
        .unwrap()
        .join("build/static/native/bin");
    let canonical = static_bin.join("ppocr_ffi.dll");
    // 缓存戳记录已构建 DLL 的架构：先构建 x64 再构建 x86（或反过来）时，
    // 不能把另一架构的缓存 DLL 打包/复制给当前目标。
    let arch_stamp = static_bin.join("ppocr_ffi.dll.arch");
    let stamp_matches = std::fs::read_to_string(&arch_stamp)
        .map(|s| s.trim() == cmake_arch)
        .unwrap_or(false);
    let target_copies: Vec<std::path::PathBuf> = [
        profile_dir.join("ppocr_ffi.dll"),
        profile_dir.join("deps").join("ppocr_ffi.dll"),
    ]
    .to_vec();

    if !sources.is_empty()
        && stamp_matches
        && artifacts_fresh(&sources, std::slice::from_ref(&canonical))
    {
        // Cache hit: reuse the already-built DLL; just make sure the copies
        // next to the app/test binaries are still in place.
        for dest in target_copies {
            if let Some(parent) = dest.parent() {
                std::fs::create_dir_all(parent)
                    .unwrap_or_else(|e| panic!("failed to create {}: {e}", parent.display()));
            }
            if !dest.exists() {
                std::fs::copy(&canonical, &dest).unwrap_or_else(|e| {
                    panic!(
                        "failed to copy cached ppocr_ffi.dll to {}: {e}",
                        dest.display()
                    )
                });
            }
        }
        println!("using cached ppocr_ffi.dll ({cmake_arch}, PP-OCR engine)");
        return;
    }

    let dst = cmake::Config::new(&ppocr_dir)
        .define("CMAKE_INSTALL_PREFIX", "")
        .define("ARCH", cmake_arch)
        // VS 生成器的目标平台（相当于命令行 -A Win32/-A x64）；决定 MSVC
        // 工具集编出的 DLL 位数。
        .define("CMAKE_GENERATOR_PLATFORM", generator_platform)
        .build_target("ppocr_ffi")
        .build();

    // The DLL bundles ncnn + opencv; the Rust side loads it at runtime.
    let dll = dst.join("build").join(config_dir).join("ppocr_ffi.dll");
    if !dll.exists() {
        panic!(
            "ppocr_ffi.dll not found after CMake build: {}",
            dll.display()
        );
    }

    // Distribute the DLL next to the app binary (dev), next to the test
    // binaries, and into the bundled resources (packaged apps). static_bin
    // 只有一份（随包分发、与包架构一致）：先构建一种架构再构建另一种时
    // 会触发整体重建，属于预期代价。
    let mut dests = vec![
        profile_dir.clone(),
        profile_dir.join("deps"),
        static_bin.clone(),
    ];
    dests.dedup();
    for dest in dests {
        std::fs::create_dir_all(&dest)
            .unwrap_or_else(|e| panic!("failed to create {}: {e}", dest.display()));
        std::fs::copy(&dll, dest.join("ppocr_ffi.dll"))
            .unwrap_or_else(|e| panic!("failed to copy ppocr_ffi.dll to {}: {e}", dest.display()));
    }
    let _ = std::fs::write(&arch_stamp, cmake_arch);
    // Info-level (shown only with `cargo build -v`).
    println!("built ppocr_ffi.dll ({cmake_arch}, PP-OCR engine)");
}

#[cfg(not(target_os = "windows"))]
fn build_ppocr() {
    // PP-OCR native capture is Windows-only.
}

#[cfg(target_os = "windows")]
fn build_cli() {
    use std::process::Command;

    let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let cli_dir = std::path::Path::new(&manifest_dir).join("native/cli");
    // Dev layout: <project>/build/static/native/bin (packaged via
    // tauri.conf.json resources `../build/static/**/*` → `static/`).
    let bin_dir = std::path::Path::new(&manifest_dir)
        .parent()
        .unwrap()
        .join("build/static/native/bin");
    let build_dir = std::path::Path::new(&manifest_dir).join("target/cli-build");

    // Same caching scheme as build_ppocr: skip CMake entirely when the CLIs
    // already exist and are newer than the sources.
    let sources = walk_files(&cli_dir);
    track_files(&cli_dir);
    let artifacts = [
        bin_dir.join("JBeijingCli.exe"),
        bin_dir.join("DrEyeCli.exe"),
    ];

    if !sources.is_empty() && artifacts_fresh(&sources, &artifacts) {
        println!("using cached JBeijingCli/DrEyeCli");
        return;
    }

    let build = || -> Result<(), String> {
        std::fs::create_dir_all(&build_dir).map_err(|e| e.to_string())?;

        let configure = Command::new("cmake")
            .args(["-G", "Visual Studio 17 2022", "-A", "Win32", "-S"])
            .arg(&cli_dir)
            .arg("-B")
            .arg(&build_dir)
            .status()
            .map_err(|e| format!("cmake configure failed: {e}"))?;
        if !configure.success() {
            return Err("cmake configure exited non-zero".into());
        }

        let compile = Command::new("cmake")
            .args(["--build"])
            .arg(&build_dir)
            .args(["--config", "Release", "--parallel"])
            .status()
            .map_err(|e| format!("cmake build failed: {e}"))?;
        if !compile.success() {
            return Err("cmake build exited non-zero".into());
        }

        std::fs::create_dir_all(&bin_dir).map_err(|e| e.to_string())?;
        for target in ["JBeijingCli.exe", "DrEyeCli.exe"] {
            let src = build_dir.join("Release").join(target);
            if !src.exists() {
                return Err(format!("{target} not found after CMake build"));
            }
            std::fs::copy(&src, bin_dir.join(target)).map_err(|e| e.to_string())?;
        }
        Ok(())
    };

    if let Err(e) = build() {
        panic!("failed to build JBeijing/DrEye CLIs: {e}");
    }
    // Info-level (shown only with `cargo build -v`).
    println!("built JBeijingCli/DrEyeCli into {}", bin_dir.display());
}

/// Recursively collect files under `dir` (used for freshness checks).
fn walk_files(dir: &Path) -> Vec<std::path::PathBuf> {
    let mut files = Vec::new();
    if let Ok(entries) = std::fs::read_dir(dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                files.extend(walk_files(&path));
            } else {
                files.push(path);
            }
        }
    }
    files
}

/// Emit `cargo:rerun-if-changed` for every native source file so Cargo does
/// not re-run this build script unless the C++ sources actually change.
fn track_files(dir: &Path) {
    for file in walk_files(dir) {
        println!("cargo:rerun-if-changed={}", file.display());
    }
}

/// True when every artifact exists and is at least as new as the newest source.
fn artifacts_fresh(sources: &[std::path::PathBuf], artifacts: &[std::path::PathBuf]) -> bool {
    let newest = sources
        .iter()
        .filter_map(|f| std::fs::metadata(f).ok())
        .filter_map(|m| m.modified().ok())
        .max();
    let Some(newest) = newest else {
        return artifacts.iter().all(|a| a.exists());
    };
    artifacts.iter().all(|a| {
        std::fs::metadata(a)
            .ok()
            .and_then(|m| m.modified().ok())
            .map(|t| t >= newest)
            .unwrap_or(false)
    })
}
