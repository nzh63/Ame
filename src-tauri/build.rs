use std::env;
use std::path::Path;

fn main() {
    // Self-check the vendored SHA-256 against FIPS known-answer vectors so a
    // broken hash implementation fails the build immediately (rather than
    // silently accepting a tampered download). Cheap — three small inputs.
    verify_sha256_selfcheck();

    // tauri-build validates that every path in `bundle.resources` exists and
    // tauri-codegen validates `frontendDist` when building without a dev URL
    // (plain `cargo build`/`cargo clippy`/`cargo test`). Both point at
    // gitignored `build/` subdirectories that don't exist on a fresh checkout:
    // `build/static` is populated by the native/asset steps below and
    // `build/render` is generated by Vite before bundling. Create them up
    // front so those cargo invocations work without a prior `yarn build:render`.
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is not set");
    let project_dir = Path::new(&manifest_dir)
        .parent()
        .expect("manifest dir has a parent");
    for dir in ["static", "render"] {
        let dir = project_dir.join("build").join(dir);
        std::fs::create_dir_all(&dir)
            .unwrap_or_else(|e| panic!("failed to create {}: {e}", dir.display()));
    }

    tauri_build::build();

    // tauri-build only embeds the Windows application manifest (Common
    // Controls v6, needed for TaskDialogIndirect etc.) into the app binary
    // via `rustc-link-arg-bins`. Unit-test binaries are linked without it and
    // then fail to start with STATUS_ENTRYPOINT_NOT_FOUND (0xC0000139) on
    // systems where comctl32 v5 lacks those entry points.
    //
    // The manifest/icon/version resources are compiled by tauri-build into
    // `resource.lib` inside OUT_DIR; link the same resource into test
    // binaries so they carry the manifest too.
    if cfg!(target_os = "windows") && env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        let out_dir = env::var("OUT_DIR").expect("OUT_DIR is not set");
        // Some CMake invocations (e.g. the cli build) can drop a stub
        // `msvcrt.lib` (only a .drectve section) into OUT_DIR. If it ends up
        // on the linker search path it shadows the real CRT and breaks every
        // link with LNK2001 memcpy. Remove it defensively.
        let stray_msvcrt = std::path::Path::new(&out_dir).join("msvcrt.lib");
        if stray_msvcrt.exists() {
            let _ = std::fs::remove_file(&stray_msvcrt);
        }
        let resource = std::path::Path::new(&out_dir).join("resource.lib");
        if resource.exists() {
            // `rustc-link-arg-tests` covers integration-test binaries; the
            // lib unit-test harness (`ame_lib-<hash>.exe`) links the resource
            // itself via the `#[cfg(test)] #[link]` directive in lib.rs.
            println!("cargo:rustc-link-arg-tests={}", resource.display());
            println!("cargo:rustc-link-search=native={}", out_dir);
        } else {
            println!("cargo:warning=resource.lib not found in OUT_DIR; test binaries may lack the Common Controls v6 manifest");
        }
    }

    // Build and link the PP-OCR C++ FFI static library (always included).
    // Requires Visual Studio + CMake; a failure aborts the build rather than
    // producing a binary without OCR support.
    build_ppocr();

    // Build the JBeijing/DrEye helper CLIs (32-bit, bundled under
    // build/static/native/bin). A failure aborts the build.
    #[cfg(target_os = "windows")]
    build_cli();

    // Download runtime assets (Textractor, PP-OCR models) into build/static.
    if let Err(e) = download_runtime_deps() {
        // Hard-fail: the app would silently lack Textractor/PP-OCR at runtime.
        panic!("failed to download runtime dependencies: {e}");
    }
}

/// Download runtime assets into `<project>/build/static`.
///
/// The Rust backend consumes these at runtime via `paths::static_dir`:
/// TextractorCLI/texthook.dll for the Textractor extractor and ncnn models
/// for the PP-OCR engine. Downloads are idempotent (skipped when the files
/// already exist). A failure aborts the build so the app never runs with
/// missing runtime files.
fn download_runtime_deps() -> Result<(), String> {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let static_dir = Path::new(&manifest_dir)
        .parent()
        .unwrap()
        .join("build/static");
    let cache_dir = Path::new(&manifest_dir).join("target/runtime-deps");

    let textractor_files = [
        "textractor/x86/TextractorCLI.exe",
        "textractor/x86/texthook.dll",
        "textractor/x64/TextractorCLI.exe",
        "textractor/x64/texthook.dll",
    ];
    let ppocr_files = [
        "ppocr/PP-OCRv5_mobile_det.fp16.ncnn.param",
        "ppocr/PP-OCRv5_mobile_det.fp16.ncnn.bin",
        "ppocr/PP-OCRv5_mobile_rec.fp16.ncnn.param",
        "ppocr/PP-OCRv5_mobile_rec.fp16.ncnn.bin",
        "ppocr/PP-OCRv5_server_det.fp32.ncnn.param",
        "ppocr/PP-OCRv5_server_det.fp32.ncnn.bin",
        "ppocr/PP-OCRv5_server_rec.fp32.ncnn.param",
        "ppocr/PP-OCRv5_server_rec.fp32.ncnn.bin",
    ];

    if !all_exist(&static_dir, &textractor_files) {
        download_textractor(&static_dir, &cache_dir)?;
    }
    if !all_exist(&static_dir, &ppocr_files) {
        download_ppocr(&static_dir)?;
    }
    Ok(())
}

fn all_exist(base: &Path, files: &[&str]) -> bool {
    files.iter().all(|f| base.join(f).exists())
}

/// Compute the SHA-256 hex digest of a file using a small build-time-only
/// implementation (FIPS 180-4), so the build script can verify downloads
/// without pulling a crypto crate into build-dependencies.
fn sha256_hex(path: &Path) -> Result<String, String> {
    let data = std::fs::read(path).map_err(|e| e.to_string())?;
    let mut h: [u32; 8] = [
        0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab,
        0x5be0cd19,
    ];
    const K: [u32; 64] = [
        0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4,
        0xab1c5ed5, 0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe,
        0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f,
        0x4a7484aa, 0x5cb0a9dc, 0x76f988da, 0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7,
        0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967, 0x27b70a85, 0x2e1b2138, 0x4d2c6dfc,
        0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b,
        0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070, 0x19a4c116,
        0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
        0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7,
        0xc67178f2,
    ];
    let bitlen = (data.len() as u64) * 8;
    let mut msg = data;
    msg.push(0x80);
    while msg.len() % 64 != 56 {
        msg.push(0);
    }
    msg.extend_from_slice(&bitlen.to_be_bytes());
    for chunk in msg.chunks(64) {
        let mut w = [0u32; 64];
        for (i, c) in chunk.chunks(4).enumerate() {
            w[i] = u32::from_be_bytes([c[0], c[1], c[2], c[3]]);
        }
        for i in 16..64 {
            let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
            let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
            w[i] = w[i - 16]
                .wrapping_add(s0)
                .wrapping_add(w[i - 7])
                .wrapping_add(s1);
        }
        let [mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut hh] = h;
        for i in 0..64 {
            let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
            let ch = (e & f) ^ (!e & g);
            let temp1 = hh
                .wrapping_add(s1)
                .wrapping_add(ch)
                .wrapping_add(K[i])
                .wrapping_add(w[i]);
            let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
            let maj = (a & b) ^ (a & c) ^ (b & c);
            let temp2 = s0.wrapping_add(maj);
            hh = g;
            g = f;
            f = e;
            e = d.wrapping_add(temp1);
            d = c;
            c = b;
            b = a;
            a = temp1.wrapping_add(temp2);
        }
        h[0] = h[0].wrapping_add(a);
        h[1] = h[1].wrapping_add(b);
        h[2] = h[2].wrapping_add(c);
        h[3] = h[3].wrapping_add(d);
        h[4] = h[4].wrapping_add(e);
        h[5] = h[5].wrapping_add(f);
        h[6] = h[6].wrapping_add(g);
        h[7] = h[7].wrapping_add(hh);
    }
    Ok(h.iter().map(|x| format!("{x:08x}")).collect::<String>())
}

/// Verify a file's SHA-256 against an expected digest; error on mismatch.
fn verify_sha256(path: &Path, expected: &str) -> Result<(), String> {
    let actual = sha256_hex(path)?;
    if actual != expected {
        return Err(format!(
            "checksum mismatch for {}: expected {expected}, got {actual}",
            path.display()
        ));
    }
    Ok(())
}

/// Build-time self-check of the vendored SHA-256 against FIPS known-answer
/// vectors. Panics (failing the build) if the implementation is wrong.
fn verify_sha256_selfcheck() {
    let check = |input: &[u8], expected: &str| {
        // Hash the bytes via a temp file (sha256_hex operates on a file).
        let dir = std::env::temp_dir().join(format!("ame-build-sha-{}", std::process::id()));
        std::fs::create_dir_all(&dir).expect("create sha selfcheck dir");
        let file = dir.join("vector.bin");
        std::fs::write(&file, input).expect("write sha selfcheck vector");
        let actual = sha256_hex(&file).expect("compute sha selfcheck");
        let _ = std::fs::remove_file(&file);
        assert_eq!(
            actual, expected,
            "vendored SHA-256 is broken (input {:?})",
            input
        );
    };
    check(
        b"",
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
    );
    check(
        b"abc",
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
    );
    check(
        b"hello world",
        "b94d27b9934d3e08a52e52d7da7dabfac484efe37a5380ee9088f7ace2efcde9",
    );
}

/// Download a file and verify its SHA-256 digest.
fn download_file_verified(url: &str, dst: &Path, expected_sha256: &str) -> Result<(), String> {
    download_file(url, dst)?;
    verify_sha256(dst, expected_sha256)
}

fn download_file(url: &str, dst: &Path) -> Result<(), String> {
    if dst.exists() {
        return Ok(());
    }
    // Info-level (shown only with `cargo build -v`).
    println!("downloading {url}");
    let result = (|| -> Result<(), String> {
        let resp = ureq::get(url).call().map_err(|e| e.to_string())?;
        let mut reader = resp.into_reader();
        if let Some(parent) = dst.parent() {
            std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        let mut file = std::fs::File::create(dst).map_err(|e| e.to_string())?;
        std::io::copy(&mut reader, &mut file).map_err(|e| e.to_string())?;
        Ok(())
    })();
    if result.is_err() {
        // Remove the partial file so the next build retries from scratch.
        let _ = std::fs::remove_file(dst);
    }
    result
}

fn download_textractor(static_dir: &Path, cache_dir: &Path) -> Result<(), String> {
    std::fs::create_dir_all(cache_dir).map_err(|e| e.to_string())?;
    let zip_path = cache_dir.join("Textractor-5.2.0-Zip-Version-English-Only.zip");
    let url = "https://github.com/Artikash/Textractor/releases/download/v5.2.0/Textractor-5.2.0-Zip-Version-English-Only.zip";
    if !zip_path.exists() {
        download_file(url, &zip_path)?;
    }

    let wanted = [
        (
            "Textractor/x86/TextractorCLI.exe",
            "textractor/x86/TextractorCLI.exe",
            "b8cebf066023db1ef5921135e0aa0f68f17bade795d910a2df58a3da2bebf233",
        ),
        (
            "Textractor/x86/texthook.dll",
            "textractor/x86/texthook.dll",
            "8fde589a24ef861c581b61829626d35d6b0fcc958aaaeca620dff630f1ed465b",
        ),
        (
            "Textractor/x64/TextractorCLI.exe",
            "textractor/x64/TextractorCLI.exe",
            "3c70e50a33fe1165e430eb3df6b9658c3a848257d294b92aab29d87632fe3783",
        ),
        (
            "Textractor/x64/texthook.dll",
            "textractor/x64/texthook.dll",
            "43b966f566e1d6362416041bfb55dc4e04aef7bcb8b5aae2da8179c24b2dd58e",
        ),
    ];
    let result = (|| -> Result<(), String> {
        let archive = std::fs::File::open(&zip_path).map_err(|e| e.to_string())?;
        let mut zip = zip::ZipArchive::new(archive).map_err(|e| e.to_string())?;
        for (entry_name, dst_rel, expected) in wanted {
            let dst = static_dir.join(dst_rel);
            if dst.exists() {
                continue;
            }
            let mut entry = zip
                .by_name(entry_name)
                .map_err(|e| format!("zip entry {entry_name}: {e}"))?;
            if let Some(parent) = dst.parent() {
                std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
            }
            let mut file = std::fs::File::create(&dst).map_err(|e| e.to_string())?;
            std::io::copy(&mut entry, &mut file).map_err(|e| e.to_string())?;
            verify_sha256(&dst, expected)?;
        }
        download_file_verified(
            "https://github.com/Artikash/Textractor/raw/master/LICENSE",
            &static_dir.join("textractor/LICENSE.Textractor.txt"),
            "8ceb4b9ee5adedde47b31e975c1d90c73ad27b6b165a1dcd80c7c545eb65b903",
        )
    })();
    if result.is_err() {
        // Drop the cached zip so a corrupt/partial download is retried.
        let _ = std::fs::remove_file(&zip_path);
    }
    result
}

